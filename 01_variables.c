#include<stdio.h>
int main(){
    int i = 10;
    int j = i;
    int a = 2, b = 3, c = 4, d = 5;
    //%d is called format specifier
    // %d is for int, %f is for float and %c is for char
    printf("the value of i is %d \nand value of j is %d", i , j);
    printf("\nthe value of a is %d \nthe value of b is %d \nthe value of c is %d \nthe value of d is %d", a, b, c, d);
    return 0;
}